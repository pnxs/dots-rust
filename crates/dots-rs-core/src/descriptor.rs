//! Static metadata describing DOTS struct types.
//!
//! These types are layout-aware: the [`StructDescriptor`] carries the
//! whole-struct `(size, align)` pair so dynamic instances ([`AnyStruct`])
//! can be heap-allocated with the same memory layout the proc-macro
//! produces for typed structs. Each [`PropertyDescriptor`] carries a
//! field offset and a [`PropertyVtable`] of typed thunks that read,
//! write, and drop the field through `*mut u8` pointers.
//!
//! The vtables are how the descriptor-driven codec stays user-type
//! agnostic at the runtime level: dotsd-style infrastructure walks the
//! descriptor and dispatches per-property without knowing the concrete
//! Rust types.
//!
//! [`AnyStruct`]: crate::layout::AnyStruct
//! [`PropertyVtable`]: PropertyVtable

use core::alloc::Layout;

use crate::layout::{CborDecoder, CborEncoder, DecodeError, EncodeError};

/// What kind of value lives behind a property's vtable.
///
/// This is metadata for introspection (e.g. logging, debugging,
/// cross-language tooling). The runtime codec dispatches via the
/// vtable thunks, not by matching on `FieldKind` — but `FieldKind`
/// is what survives a wire-only descriptor (one received over the
/// network without compiled thunks).
///
/// Equality compares structs by descriptor pointer identity, since
/// descriptors are `'static` and unique per type.
///
/// `repr(C, u8)` with explicit discriminants because — like
/// [`StructDescriptor`] — the layout is an external contract read by
/// `dots-inspect` straight out of compiled binaries: discriminant byte
/// at offset 0, variant payload (if any) at offset 8. The discriminant
/// values are ABI; only append new variants, never renumber.
#[derive(Debug, Clone, Copy)]
#[repr(C, u8)]
pub enum FieldKind {
    Bool = 0,
    U8 = 1, U16 = 2, U32 = 3, U64 = 4,
    I8 = 5, I16 = 6, I32 = 7, I64 = 8,
    F32 = 9, F64 = 10,
    PropertySet = 11,

    /// Wall-clock time (`f64` seconds since Unix epoch on the wire).
    Timepoint = 12,

    /// Fractional-second duration (`f64` seconds on the wire).
    Duration = 13,

    String = 14,
    /// DOTS `uuid` — exactly 16 raw bytes (CBOR ByteString of length
    /// 16 on the wire). The *only* fixed-byte type in DOTS; arbitrary
    /// binary blobs should use `Vec(U8)` (DOTS `vector<uint8>`),
    /// matching dots-cpp.
    Uuid = 15,

    /// Homogeneous array of `inner`.
    Vec(&'static FieldKind) = 16,
    /// Nested DOTS struct, statically known at compile time.
    Struct(&'static StructDescriptor) = 17,
    /// DOTS enum, statically known at compile time.
    Enum(&'static EnumDescriptor) = 18,

    /// Open `any` — an arbitrary DOTS object stored inside a single
    /// property as a self-describing, opaque CBOR envelope
    /// (`[type-name, payload-bytes]`). Unlike a nested `Struct`, the
    /// contained type is *not* derivable from the static schema, so the
    /// type identity travels inside the value. The runtime
    /// representation is [`crate::AnyObject`]; recovering the stored
    /// object is an explicit, registry-resolved decode step
    /// (`crate::AnyObject` + the broker's `Registry::from_any`).
    Any = 19,
}

impl FieldKind {
    /// Whether this kind is legal for a `#[dots(key)]` property
    /// (wire-format spec §6.3): scalars whose deterministic encoding
    /// makes byte equality valid identity. Floats, temporal types,
    /// `property_set`, vectors, nested structs, and `any` are not —
    /// their equality is not byte-stable (or, for `property_set`, not
    /// an identity).
    pub const fn is_valid_key_kind(&self) -> bool {
        matches!(
            self,
            Self::Bool
                | Self::U8
                | Self::U16
                | Self::U32
                | Self::U64
                | Self::I8
                | Self::I16
                | Self::I32
                | Self::I64
                | Self::String
                | Self::Uuid
                | Self::Enum(_)
        )
    }
}

impl PartialEq for FieldKind {
    fn eq(&self, other: &Self) -> bool {
        use FieldKind::*;
        match (self, other) {
            (Bool, Bool) | (U8, U8) | (U16, U16) | (U32, U32) | (U64, U64)
            | (I8, I8) | (I16, I16) | (I32, I32) | (I64, I64)
            | (F32, F32) | (F64, F64)
            | (String, String) | (Uuid, Uuid)
            | (Timepoint, Timepoint) | (Duration, Duration)
            | (Any, Any) => true,
            (Vec(a), Vec(b)) => core::ptr::eq(*a, *b) || a == b,
            (Struct(a), Struct(b)) => core::ptr::eq(*a, *b),
            (Enum(a), Enum(b)) => core::ptr::eq(*a, *b),
            _ => false,
        }
    }
}

impl Eq for FieldKind {}

/// Per-property thunks operating on a typed `Option<T>` accessed via
/// raw pointer arithmetic from a struct base address.
///
/// Generated by `#[derive(DotsStruct)]` for each field. The thunks are
/// monomorphic — they know `T` — but expose a uniform pointer-based
/// interface so the descriptor-walker is type-agnostic.
///
/// All four functions are `unsafe fn`; the safety contract for each is
/// the same: the supplied pointer must point to a valid `Option<T>`
/// instance whose lifetime exceeds the call. A zero-initialized buffer
/// of the right `(size, align)` always satisfies this for `Option<T>`
/// because `None` is bit-pattern zero for every primitive `T` plus
/// `String`, `Vec<T>`, and `Box<_>` (niche optimization).
pub struct PropertyVtable {
    /// Layout of the field's storage type — `Option<T>` for ordinary
    /// (optional) properties, or bare `T` for `#[dots(key)]` properties
    /// stored unwrapped. Used for sub-validation and (later) potential
    /// per-property allocation strategies.
    pub layout: Layout,

    /// Initialize a freshly zero-allocated slot to a valid value.
    ///
    /// For `Option<T>` fields this is a no-op: the zeroed buffer is
    /// already a valid `None`. For bare-`T` key fields (whose zeroed
    /// bits may be an *invalid* `T`, e.g. a null-pointer `String`) this
    /// writes a valid `T::default()` so the slot is always sound to
    /// read, drop, and overwrite. Called once per property by
    /// [`AnyStruct::new`](crate::layout::AnyStruct::new) right after
    /// zero-allocation, keeping the buffer fully valid at all times.
    pub init: unsafe fn(*mut u8),

    /// Returns whether the property is `Some(_)`. Bare-`T` key fields
    /// are always set, so their thunk returns `true` unconditionally.
    pub is_set: unsafe fn(*const u8) -> bool,

    /// Reads the inner `T` (assumes `Some(_)`) and writes it to the
    /// encoder. Caller pre-counted via `is_set` so this is only called
    /// on populated fields.
    pub encode_value: unsafe fn(*const u8, &mut CborEncoder<'_>) -> Result<(), EncodeError>,

    /// Decodes a `T` from the decoder, drops any existing `Option<T>`
    /// at the destination, and writes `Some(value)` in its place.
    pub decode_value: unsafe fn(*mut u8, &mut CborDecoder<'_>) -> Result<(), DecodeError>,

    /// Drops the `Option<T>` at the pointer in place. Safe to call on
    /// a `None`, which is a no-op. Must be called exactly once per
    /// initialized field before the buffer is freed.
    pub drop_in_place: unsafe fn(*mut u8),

    /// Deep-clones the `Option<T>` at `src` into `dst`. The `dst`
    /// location must be a valid `Option<T>` (e.g. zero-initialized,
    /// which reads as `None`); any previous value is dropped before
    /// the clone is written. Used by `AnyStruct::clone`.
    pub clone_in_place: unsafe fn(src: *const u8, dst: *mut u8),

    /// Clears the property at the pointer, dropping any existing value.
    /// For `Option<T>` fields this drops the old value and writes a
    /// real `None` (never relying on a zero bit-pattern — niche layouts
    /// like `Option<bool>` or `Option<AnyObject>` don't put `None` at
    /// zero). For bare-`T` key fields — which `AnyStruct::copy_from`
    /// never clears — it restores `T::default()` so the slot stays a
    /// valid, droppable `T`. Used by `AnyStruct::copy_from` to apply
    /// the "property named in the update mask but absent from the
    /// payload" (explicit-clear) case.
    pub set_none: unsafe fn(*mut u8),

    /// Moves the property at `src` into `dst`, dropping any existing
    /// value at `dst` and leaving `src` cleared (`None` for an
    /// `Option<T>`, `T::default()` for a bare-`T` key). Unlike
    /// `clone_in_place`, this transfers owned heap data (`String`/`Vec`
    /// buffers, nested allocations) without deep-cloning it — the
    /// allocation is handed over, not copied.
    ///
    /// Used by `AnyStruct::copy_take` on the cache's update path when
    /// the incoming value is owned and about to be dropped, so its
    /// fields are moved into the stored entry instead of cloned.
    pub take_in_place: unsafe fn(src: *mut u8, dst: *mut u8),

    /// Compares the full slots at `lhs` and `rhs` — validity *and*
    /// value. Two `None`s are equal, `None` ≠ `Some(_)`, and two
    /// `Some`s compare their inner values via
    /// [`DotsFieldOps::dots_eq`](crate::DotsFieldOps::dots_eq).
    /// Coherent with `cmp_in_place`: equal ⇔ `Ordering::Equal`.
    pub eq_in_place: unsafe fn(lhs: *const u8, rhs: *const u8) -> bool,

    /// Total order over the full slots at `lhs` and `rhs`. `None`
    /// sorts before any `Some(_)` — the same convention dots-cpp uses
    /// (an invalid property is less than any valid one). Floats use
    /// `total_cmp`, so the order is total even in the presence of NaN
    /// (a deliberate divergence from C++'s IEEE `<`).
    pub cmp_in_place: unsafe fn(lhs: *const u8, rhs: *const u8) -> core::cmp::Ordering,

    /// Swaps the two slots in place (validity and value). Both slots
    /// stay valid; owned heap data changes sides without cloning.
    pub swap_in_place: unsafe fn(a: *mut u8, b: *mut u8),

    /// Merges the slot at `src` into `dst` with dots-cpp `_merge`
    /// semantics: `src` unset → `dst` untouched; `src` set and `dst`
    /// unset → deep-clone; both set → recursive
    /// [`DotsFieldOps::dots_merge`](crate::DotsFieldOps::dots_merge)
    /// (property-wise for struct-typed fields, clone-assign for
    /// everything else).
    pub merge_in_place: unsafe fn(src: *const u8, dst: *mut u8),
}

impl core::fmt::Debug for PropertyVtable {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("PropertyVtable")
            .field("layout", &self.layout)
            .finish_non_exhaustive()
    }
}

/// Compile-time metadata about a single DOTS property (one struct field).
///
/// `repr(C)` for the same reason as [`StructDescriptor`]: `dots-inspect`
/// reads these out of compiled binaries.
#[derive(Debug)]
#[repr(C)]
pub struct PropertyDescriptor {
    /// Field name in the source struct.
    pub name: &'static str,
    /// DOTS wire tag (1-based).
    pub tag: u32,
    /// Whether this property participates in the struct's primary key.
    pub is_key: bool,
    /// Byte offset from the parent struct's base — `offset_of!(Foo, field)`.
    pub offset: usize,
    /// Static type tag for introspection.
    pub kind: FieldKind,
    /// Typed read/write/drop thunks.
    pub vtable: &'static PropertyVtable,
}

/// Struct-level flags from the `.dots` model.
///
/// Stored as a packed `u8` so the whole `StructDescriptor` is `const`-constructible.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct StructFlags(u8);

impl StructFlags {
    const CACHED: u8 = 1 << 0;
    const INTERNAL: u8 = 1 << 1;
    const PERSISTENT: u8 = 1 << 2;
    const CLEANUP: u8 = 1 << 3;
    const LOCAL: u8 = 1 << 4;
    const SUBSTRUCT_ONLY: u8 = 1 << 5;

    pub const NONE: Self = Self(0);

    /// Union of all defined flag bits. Bits outside this mask are
    /// unknown to this version of dots-rs — `dots-inspect` uses that
    /// as a layout-mismatch signal when reading descriptors out of
    /// compiled binaries.
    pub const ALL_KNOWN: Self = Self(
        Self::CACHED
            | Self::INTERNAL
            | Self::PERSISTENT
            | Self::CLEANUP
            | Self::LOCAL
            | Self::SUBSTRUCT_ONLY,
    );

    #[inline]
    pub const fn from_bits(bits: u8) -> Self {
        Self(bits)
    }

    #[inline]
    pub const fn bits(self) -> u8 {
        self.0
    }

    #[inline]
    pub const fn cached(self, on: bool) -> Self {
        Self(if on { self.0 | Self::CACHED } else { self.0 & !Self::CACHED })
    }
    #[inline]
    pub const fn internal(self, on: bool) -> Self {
        Self(if on { self.0 | Self::INTERNAL } else { self.0 & !Self::INTERNAL })
    }
    #[inline]
    pub const fn persistent(self, on: bool) -> Self {
        Self(if on { self.0 | Self::PERSISTENT } else { self.0 & !Self::PERSISTENT })
    }
    #[inline]
    pub const fn cleanup(self, on: bool) -> Self {
        Self(if on { self.0 | Self::CLEANUP } else { self.0 & !Self::CLEANUP })
    }
    #[inline]
    pub const fn local(self, on: bool) -> Self {
        Self(if on { self.0 | Self::LOCAL } else { self.0 & !Self::LOCAL })
    }
    #[inline]
    pub const fn substruct_only(self, on: bool) -> Self {
        Self(if on { self.0 | Self::SUBSTRUCT_ONLY } else { self.0 & !Self::SUBSTRUCT_ONLY })
    }

    #[inline]
    pub const fn is_cached(self) -> bool {
        (self.0 & Self::CACHED) != 0
    }
    #[inline]
    pub const fn is_internal(self) -> bool {
        (self.0 & Self::INTERNAL) != 0
    }
    #[inline]
    pub const fn is_persistent(self) -> bool {
        (self.0 & Self::PERSISTENT) != 0
    }
    #[inline]
    pub const fn is_cleanup(self) -> bool {
        (self.0 & Self::CLEANUP) != 0
    }
    #[inline]
    pub const fn is_local(self) -> bool {
        (self.0 & Self::LOCAL) != 0
    }
    #[inline]
    pub const fn is_substruct_only(self) -> bool {
        (self.0 & Self::SUBSTRUCT_ONLY) != 0
    }
}

/// Compile-time metadata about a DOTS struct.
///
/// Held as a `&'static StructDescriptor` constant on each generated type
/// (e.g. `MyType::DESCRIPTOR`). The `(size, align)` pair lets dynamic
/// `AnyStruct` instances allocate buffers whose layout matches the typed
/// struct exactly — so `&AnyStruct.data` is bit-identical with `&Foo`.
///
/// `repr(C)` because the layout is an external contract: `dots-inspect`
/// reads these statics out of compiled ELF binaries (following the
/// pointers in the `linkme_PUBLISHED_TYPES` / `linkme_SUBSCRIBED_TYPES`
/// sections) without running them, so field offsets must not shift with
/// compiler versions. `dots-inspect` derives its offsets via
/// `offset_of!` on this very type, so adding or reordering fields stays
/// safe as long as both sides are built from the same source.
#[derive(Debug)]
#[repr(C)]
pub struct StructDescriptor {
    pub name: &'static str,
    pub flags: StructFlags,
    /// `core::mem::size_of::<Foo>()` for the corresponding typed struct.
    pub size: usize,
    /// `core::mem::align_of::<Foo>()` for the corresponding typed struct.
    pub align: usize,
    pub properties: &'static [PropertyDescriptor],
}

impl StructDescriptor {
    /// Look up a property by tag. Linear scan — typically fewer than a
    /// dozen properties so this is fine.
    pub fn property(&self, tag: u32) -> Option<&'static PropertyDescriptor> {
        self.properties.iter().find(|p| p.tag == tag)
    }

    /// Iterate just the key properties.
    pub fn key_properties(&self) -> impl Iterator<Item = &'static PropertyDescriptor> {
        self.properties.iter().filter(|p| p.is_key)
    }

    /// Bitmask of all `#[dots(key)]` property tags. Every valid instance
    /// of this type must have at least these properties set; decoding
    /// rejects any wire value whose set of present tags doesn't include
    /// the whole mask. For bare-`T` keys this is the contract that makes
    /// the unwrapped storage sound.
    pub fn key_mask(&self) -> crate::PropertySet {
        let mut set = crate::PropertySet::EMPTY;
        for prop in self.properties {
            if prop.is_key {
                set = set.with_tag(prop.tag);
            }
        }
        set
    }

    /// Bitmask of *all* property tags this type declares — the
    /// analogue of dots-cpp's `Struct::_properties()`. Intersect a
    /// caller-supplied mask with this to trim bits that don't name a
    /// real property.
    pub fn property_mask(&self) -> crate::PropertySet {
        let mut set = crate::PropertySet::EMPTY;
        for prop in self.properties {
            set = set.with_tag(prop.tag);
        }
        set
    }

    /// `Layout` matching the typed struct — used by `AnyStruct::new` to
    /// allocate a layout-compatible buffer.
    pub fn layout(&self) -> Layout {
        // Safe by construction: `size` and `align` come from
        // `core::mem::size_of::<T>()` / `align_of::<T>()` of an actual
        // Rust type, which always satisfy `Layout`'s invariants.
        Layout::from_size_align(self.size, self.align)
            .expect("StructDescriptor size/align came from a real Rust type")
    }
}

/// Compile-time metadata about a single DOTS enum variant.
///
/// `repr(C)` for the same reason as [`StructDescriptor`]: `dots-inspect`
/// reads these out of compiled binaries.
#[derive(Debug, Clone, Copy)]
#[repr(C)]
pub struct EnumElement {
    /// Variant name in the source enum.
    pub name: &'static str,
    /// DOTS metadata tag for this variant (1-based). This is what an
    /// enum is encoded as in instance payloads (CBOR unsigned int),
    /// matching dots-cpp's `CborSerializer`.
    pub tag: u32,
    /// `int32` value associated with the variant. Descriptor metadata
    /// only (exchanged as `EnumElementDescriptor.enum_value`); never
    /// transmitted in instance payloads. Defaults to `tag - 1`, the
    /// dots-cpp code-generator default, but the `.dots` model permits
    /// an explicit override.
    pub value: i32,
}

/// Compile-time metadata about a DOTS enum.
///
/// Held as a `&'static EnumDescriptor` constant on each generated enum
/// (e.g. `MyEnum::DESCRIPTOR`). Enums are encoded on the wire as their
/// `u32` `tag`; the descriptor maps wire tags back to variants.
///
/// `repr(C)` for the same reason as [`StructDescriptor`]: `dots-inspect`
/// reads these out of compiled binaries.
#[derive(Debug, Clone, Copy)]
#[repr(C)]
pub struct EnumDescriptor {
    pub name: &'static str,
    pub elements: &'static [EnumElement],
}

impl EnumDescriptor {
    /// Look up a variant by its `int32` metadata value.
    pub fn element_by_value(&self, value: i32) -> Option<&'static EnumElement> {
        self.elements.iter().find(|e| e.value == value)
    }

    /// Look up a variant by metadata tag (the wire encoding).
    pub fn element_by_tag(&self, tag: u32) -> Option<&'static EnumElement> {
        self.elements.iter().find(|e| e.tag == tag)
    }
}

/// Statically-known [`FieldKind`] for a Rust type, supplied by the
/// `#[derive(DotsStruct)]` and `#[derive(DotsEnum)]` proc-macros.
///
/// The parent struct's macro uses `<T as DotsTypeKind>::KIND` as its
/// fallback for unknown nested types — that single trait covers both
/// nested DOTS structs (`FieldKind::Struct(...)`) and DOTS enums
/// (`FieldKind::Enum(...)`) without the parent macro needing to tell
/// them apart.
pub trait DotsTypeKind {
    const KIND: FieldKind;
}
